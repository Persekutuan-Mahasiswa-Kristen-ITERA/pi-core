#!/usr/bin/env node
/**
 * Verify a PI-CORE OAuth client secret against the hash stored in the database.
 *
 * Usage:
 *   1. Get the stored hash from the DB:
 *        SELECT client_id, client_secret FROM oauth_clients WHERE client_id = '...';
 *   2. Run this script:
 *        node scripts/verify-client-secret.mjs
 *   3. Paste the DB hash and the plaintext secret.
 *
 * This replicates Better Auth's `defaultHasher` (SHA-256, base64url, no padding)
 * so you can verify locally without hitting the server.
 */

import readline from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";

const rl = readline.createInterface({ input, output });

console.log("═══════════════════════════════════════════════════════════");
console.log("  Better Auth client_secret hash verifier");
console.log("  (SHA-256, base64url, no padding — same as defaultHasher)");
console.log("═══════════════════════════════════════════════════════════\n");

const storedHash = (
  await rl.question("Stored hash from DB (client_secret column): ")
).trim();
const plaintext = (await rl.question("Plaintext secret to verify: ")).trim();
rl.close();

if (!storedHash || !plaintext) {
  console.error("Both values are required.");
  process.exit(1);
}

// Replicate Better Auth's defaultHasher EXACTLY:
// Uses Web Crypto SubtleCrypto.digest('SHA-256', ...) → base64url encode without padding.
// This is the same code path used inside Cloudflare Workers and Node.
const hashBuffer = await crypto.subtle.digest(
  "SHA-256",
  new TextEncoder().encode(plaintext),
);
const computed = Buffer.from(hashBuffer).toString("base64url"); // base64url, no padding

console.log(`\nStored hash:   ${storedHash}`);
console.log(`Computed hash: ${computed}`);

if (computed === storedHash) {
  console.log(
    "\n✅ MATCH — the plaintext secret is correct for this stored hash.",
  );
} else {
  console.log("\n❌ MISMATCH — the plaintext does NOT match the stored hash.");
  console.log("   Possible causes:");
  console.log("   1. You're using the old secret (before rotation).");
  console.log(
    "   2. You're using the Google client secret (GOCSPX-…) instead of the PI-CORE OAuth client secret.",
  );
  console.log(
    "   3. The secret was generated by a different BETTER_AUTH_SECRET or different crypto implementation.",
  );
  console.log("   4. Copy-paste error (extra spaces, newlines, etc.).");
}
